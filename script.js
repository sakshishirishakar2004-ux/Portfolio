let currentProjectIndex = 0;
let currentImageIndex = 0;
let isImageZoomed = false;


document.addEventListener('DOMContentLoaded', () => {
  if (typeof lucide !== 'undefined') {
    lucide.createIcons();
  }

  setupMobileNavigation();
  setupFilterTabs();
  setupContactForm();
  setupModalControls();
});

function setupMobileNavigation() {
  const toggleBtn = document.getElementById('mobileMenuToggle');
  const drawer = document.getElementById('mobileDrawer');
  const openIcon = document.getElementById('menuOpenIcon');
  const closeIcon = document.getElementById('menuCloseIcon');
  const mobileLinks = document.querySelectorAll('.mobile-nav-link');

  if (!toggleBtn || !drawer) return;

  toggleBtn.addEventListener('click', () => {
    const isClosed = drawer.classList.contains('hidden-element');
    if (isClosed) {
      drawer.classList.remove('hidden-element');
      openIcon.classList.add('hidden-element');
      closeIcon.classList.remove('hidden-element');
    } else {
      drawer.classList.add('hidden-element');
      openIcon.classList.remove('hidden-element');
      closeIcon.classList.add('hidden-element');
    }
  });

  mobileLinks.forEach((link) => {
    link.addEventListener('click', () => {
      drawer.classList.add('hidden-element');
      openIcon.classList.remove('hidden-element');
      closeIcon.classList.add('hidden-element');
    });
  });
}

function setupFilterTabs() {
  const tabs = document.querySelectorAll('.filter-tab');
  const projectCards = document.querySelectorAll('#projectsContainer > .project-card, #projectsContainer > .editorial-duo-grid');

  tabs.forEach((tab) => {
    tab.addEventListener('click', () => {
      tabs.forEach((t) => t.classList.remove('active'));
      tab.classList.add('active');

      const filterValue = tab.getAttribute('data-filter');

      projectCards.forEach((card) => {
        if (card.classList.contains('editorial-duo-grid')) {
          const subArticles = card.querySelectorAll('.project-card');
          let visibleSubCount = 0;
          subArticles.forEach((sub) => {
            const subCategory = sub.getAttribute('data-category');
            if (filterValue === 'ALL' || subCategory === filterValue) {
              sub.style.display = 'block';
              visibleSubCount++;
            } else {
              sub.style.display = 'none';
            }
          });
          card.style.display = visibleSubCount > 0 ? 'grid' : 'none';
        } else {
          const category = card.getAttribute('data-category');
          if (filterValue === 'ALL' || category === filterValue) {
            card.style.display = 'block';
          } else {
            card.style.display = 'none';
          }
        }
      });
    });
  });
}

function setupModalControls() {
  const modal = document.getElementById('artworkModal');
  const closeBtn = document.getElementById('modalCloseBtn');
  const prevBtn = document.getElementById('modalPrevBtn');
  const nextBtn = document.getElementById('modalNextBtn');
  const zoomBtn = document.getElementById('modalZoomBtn');
  const mainImg = document.getElementById('modalMainImg');

  if (!modal) return;

  closeBtn.addEventListener('click', closeModal);
  modal.addEventListener('click', (e) => {
    if (e.target === modal) closeModal();
  });

  prevBtn.addEventListener('click', () => {
    currentProjectIndex = (currentProjectIndex - 1 + PORTFOLIO_PROJECTS.length) % PORTFOLIO_PROJECTS.length;
    currentImageIndex = 0;
    renderModalContent();
  });

  nextBtn.addEventListener('click', () => {
    currentProjectIndex = (currentProjectIndex + 1) % PORTFOLIO_PROJECTS.length;
    currentImageIndex = 0;
    renderModalContent();
  });

  zoomBtn.addEventListener('click', toggleZoom);
  mainImg.addEventListener('click', toggleZoom);

  document.addEventListener('keydown', (e) => {
    if (modal.classList.contains('hidden-element')) return;
    if (e.key === 'Escape') closeModal();
    if (e.key === 'ArrowRight') nextBtn.click();
    if (e.key === 'ArrowLeft') prevBtn.click();
  });
}

function openModalById(projectId, imageIdx = 0) {
  const index = PORTFOLIO_PROJECTS.findIndex((p) => p.id === projectId);
  if (index === -1) return;

  currentProjectIndex = index;
  currentImageIndex = imageIdx;
  isImageZoomed = false;

  const modal = document.getElementById('artworkModal');
  modal.classList.remove('hidden-element');
  document.body.style.overflow = 'hidden';

  renderModalContent();
}

function closeModal() {
  const modal = document.getElementById('artworkModal');
  modal.classList.add('hidden-element');
  document.body.style.overflow = 'unset';
  isImageZoomed = false;
  resetZoomState();
}

function toggleZoom() {
  isImageZoomed = !isImageZoomed;
  const mainImg = document.getElementById('modalMainImg');
  const zoomInIcon = document.getElementById('zoomInIcon');
  const zoomOutIcon = document.getElementById('zoomOutIcon');
  const zoomBtnText = document.getElementById('zoomBtnText');

  if (isImageZoomed) {
    mainImg.classList.add('zoomed');
    zoomInIcon.classList.add('hidden-element');
    zoomOutIcon.classList.remove('hidden-element');
    zoomBtnText.textContent = 'RESET';
  } else {
    resetZoomState();
  }
}

function resetZoomState() {
  const mainImg = document.getElementById('modalMainImg');
  const zoomInIcon = document.getElementById('zoomInIcon');
  const zoomOutIcon = document.getElementById('zoomOutIcon');
  const zoomBtnText = document.getElementById('zoomBtnText');

  if (!mainImg) return;
  mainImg.classList.remove('zoomed');
  zoomInIcon.classList.remove('hidden-element');
  zoomOutIcon.classList.add('hidden-element');
  zoomBtnText.textContent = 'INSPECT';
}

function renderModalContent() {
  const project = PORTFOLIO_PROJECTS[currentProjectIndex];
  if (!project) return;

  resetZoomState();

  const allImages = project.secondaryImages && project.secondaryImages.length > 0
    ? project.secondaryImages
    : [{ url: project.primaryImage, caption: project.title }];

  if (currentImageIndex >= allImages.length) {
    currentImageIndex = 0;
  }

  const currentImgData = allImages[currentImageIndex];

  document.getElementById('modalNumber').textContent = project.number;
  document.getElementById('modalCategory').textContent = `${project.category} · ${project.subCategory || ''}`;
  document.getElementById('modalCounter').textContent = `PROJECT ${currentProjectIndex + 1} OF ${PORTFOLIO_PROJECTS.length}`;
  document.getElementById('modalTitle').textContent = project.title;
  document.getElementById('modalDescription').textContent = project.longDescription || project.description;

  const mainImg = document.getElementById('modalMainImg');
  mainImg.src = currentImgData.url;
  mainImg.alt = currentImgData.caption || project.title;

  const highlightsContainer = document.getElementById('modalHighlights');
  highlightsContainer.innerHTML = '';
  project.highlights.forEach((item) => {
    const li = document.createElement('li');
    li.textContent = item;
    highlightsContainer.appendChild(li);
  });

  const toolsContainer = document.getElementById('modalTools');
  toolsContainer.innerHTML = '';
  project.tools.forEach((tool) => {
    const span = document.createElement('span');
    span.className = 'modal-tool-pill';
    span.textContent = tool;
    toolsContainer.appendChild(span);
  });

  const thumbnailsStrip = document.getElementById('modalThumbnailsStrip');
  thumbnailsStrip.innerHTML = '';

  if (allImages.length > 1) {
    thumbnailsStrip.style.display = 'flex';
    allImages.forEach((imgObj, idx) => {
      const thumbBtn = document.createElement('button');
      thumbBtn.type = 'button';
      thumbBtn.className = `modal-thumb-btn ${idx === currentImageIndex ? 'active' : ''}`;
      thumbBtn.setAttribute('aria-label', `View image ${idx + 1}`);

      const imgElem = document.createElement('img');
      imgElem.src = imgObj.url;
      imgElem.alt = imgObj.caption || `Thumbnail ${idx + 1}`;

      thumbBtn.appendChild(imgElem);
      thumbBtn.addEventListener('click', () => {
        currentImageIndex = idx;
        renderModalContent();
      });

      thumbnailsStrip.appendChild(thumbBtn);
    });
  } else {
    thumbnailsStrip.style.display = 'none';
  }

  if (typeof lucide !== 'undefined') {
    lucide.createIcons();
  }
}

document.getElementById('portfolioContactForm').addEventListener('submit', function(e) {
    e.preventDefault();
    
    const form = this;
    const submitBtn = document.getElementById('formSubmitBtn');
    const successAlert = document.getElementById('formSuccessAlert');
    
    submitBtn.disabled = true;
    submitBtn.style.opacity = '0.7';

    const formData = new FormData(form);

    fetch('contact.php', {
        method: 'POST',
        body: formData
    })
    .then(response => response.json().then(data => ({ status: response.status, body: data })))
    .then(result => {
        if (result.status === 200) {
         
            successAlert.classList.remove('hidden-element');
            form.reset();
            
            setTimeout(() => {
                successAlert.classList.add('hidden-element');
            }, 6000);
        } else {
            alert(result.body.message || 'Something went wrong. Please try again.');
        }
    })
    .catch(error => {
        console.error('Error:', error);
        alert('Network error. Please check your connection and try again.');
    })
    .finally(() => {
        submitBtn.disabled = false;
        submitBtn.style.opacity = '1';
    });
});
function setupContactForm() {
  const form = document.getElementById('portfolioContactForm');
  const submitBtn = document.getElementById('formSubmitBtn');
  const alertBox = document.getElementById('formSuccessAlert');

  if (!form) return;

  form.addEventListener('submit', (e) => {
    e.preventDefault();

    submitBtn.disabled = true;
    submitBtn.innerHTML = `
      <i data-lucide="loader-2" class="spin-icon"></i>
      <span>TRANSMITTING...</span>
    `;
    if (typeof lucide !== 'undefined') {
      lucide.createIcons();
    }

    setTimeout(() => {
      alertBox.classList.remove('hidden-element');
      form.reset();
      submitBtn.disabled = false;
      submitBtn.innerHTML = `
        <i data-lucide="check"></i>
        <span>MESSAGE TRANSMITTED!</span>
      `;
      if (typeof lucide !== 'undefined') {
        lucide.createIcons();
      }

      setTimeout(() => {
        submitBtn.innerHTML = `
          <i data-lucide="send"></i>
          <span>TRANSMIT INQUIRY</span>
        `;
        if (typeof lucide !== 'undefined') {
          lucide.createIcons();
        }
      }, 4000);
    }, 800);
  });
}